import React, { useState, useEffect } from 'react';
import { DailyBriefing, NewsArticle, NewsPreferences } from './NewsTypes';
import { NewsAIService } from './NewsAIService';
import { NewsService } from './NewsService';
import { Play, Pause, RefreshCw, Calendar, Sparkles, Clock, Compass, Share2, CheckCircle2 } from 'lucide-react';

interface NewsDailyBriefingViewProps {
  preferences: NewsPreferences;
  onSelectArticle: (article: NewsArticle) => void;
  onPlayAudio?: (text: string, title: string) => void;
}

export const NewsDailyBriefingView: React.FC<NewsDailyBriefingViewProps> = ({
  preferences,
  onSelectArticle,
  onPlayAudio,
}) => {
  const [briefingTime, setBriefingTime] = useState<'morning' | 'evening'>('morning');
  const [loading, setLoading] = useState(false);
  const [briefing, setBriefing] = useState<DailyBriefing | null>(null);
  const [isPlaying, setIsPlaying] = useState(false);
  const [copied, setCopied] = useState(false);

  const handleGenerateBriefing = async () => {
    setLoading(true);
    try {
      const articles = await NewsService.fetchNewsFeed({ category: 'top', region: preferences.region || 'US' });
      const data = await NewsAIService.generateDailyBriefing(
        articles,
        preferences.favoriteTopics || [],
        briefingTime === 'morning' ? 'Morning' : 'Evening',
        'Medium'
      );
      setBriefing(data);
    } catch (err) {
      console.error('Failed to generate daily briefing', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    handleGenerateBriefing();
  }, [briefingTime]);

  const toggleAudio = () => {
    if (!briefing) return;
    if (isPlaying) {
      window.speechSynthesis.cancel();
      setIsPlaying(false);
    } else {
      const title = briefing.title || `${briefing.timeOfDay} AI Briefing`;
      const fullSpeechText = `${title}. ${briefing.audioScript || ''}`;
      if (onPlayAudio) {
        onPlayAudio(fullSpeechText, title);
      } else {
        window.speechSynthesis.cancel();
        const utterance = new SpeechSynthesisUtterance(fullSpeechText);
        utterance.rate = preferences.playbackSpeed || 1;
        utterance.onend = () => setIsPlaying(false);
        utterance.onerror = () => setIsPlaying(false);
        window.speechSynthesis.speak(utterance);
      }
      setIsPlaying(true);
    }
  };

  const handleShare = () => {
    if (!briefing) return;
    const title = briefing.title || `${briefing.timeOfDay} AI Briefing`;
    const bullets = briefing.topBullets || briefing.topHighlights || [];
    const text = `${title}\n\nKey Takeaways:\n${bullets.map((b: string) => `• ${b}`).join('\n')}\n\nGenerated by SUPERAI NEWS 2.0`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const bullets = briefing?.topBullets || briefing?.topHighlights || [];
  const sections = briefing?.sections || briefing?.categorySummaries?.map((c) => ({
    category: c.categoryLabel,
    topicTitle: c.categoryLabel,
    summary: c.summary,
    articles: c.articles,
  })) || [];

  return (
    <div className="space-y-6 max-w-5xl mx-auto pb-12">
      {/* Header Banner */}
      <div className="relative overflow-hidden rounded-2xl bg-gradient-to-r from-blue-900 via-indigo-900 to-slate-900 text-white p-6 sm:p-8 shadow-xl border border-blue-500/20">
        <div className="absolute top-0 right-0 -mt-6 -mr-6 w-48 h-48 bg-blue-500/10 rounded-full blur-3xl pointer-events-none" />
        
        <div className="relative z-10 flex flex-col md:flex-row md:items-center justify-between gap-6">
          <div className="space-y-2">
            <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-blue-500/20 text-blue-300 text-xs font-semibold border border-blue-400/30">
              <Sparkles className="w-3.5 h-3.5" /> AI Executive Intelligence
            </div>
            <h2 className="text-2xl sm:text-3xl font-extrabold tracking-tight">
              My Daily AI Briefing
            </h2>
            <p className="text-slate-300 text-sm max-w-xl">
              Synthesized from current global headlines, tailored to your topics of interest ({(preferences.favoriteTopics || []).join(', ') || 'Global Top Headlines'}).
            </p>
          </div>

          <div className="flex flex-wrap items-center gap-3">
            {/* Morning / Evening Toggle */}
            <div className="bg-slate-800/80 p-1 rounded-xl border border-slate-700/60 inline-flex">
              <button
                onClick={() => setBriefingTime('morning')}
                className={`px-4 py-2 rounded-lg text-xs font-semibold transition-all ${
                  briefingTime === 'morning'
                    ? 'bg-blue-600 text-white shadow-sm'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                🌅 Morning Briefing
              </button>
              <button
                onClick={() => setBriefingTime('evening')}
                className={`px-4 py-2 rounded-lg text-xs font-semibold transition-all ${
                  briefingTime === 'evening'
                    ? 'bg-indigo-600 text-white shadow-sm'
                    : 'text-slate-400 hover:text-white'
                }`}
              >
                🌆 Evening Recap
              </button>
            </div>

            <button
              onClick={handleGenerateBriefing}
              disabled={loading}
              className="px-4 py-2 bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 rounded-xl text-xs font-medium inline-flex items-center gap-2 transition-all disabled:opacity-50"
            >
              <RefreshCw className={`w-3.5 h-3.5 ${loading ? 'animate-spin' : ''}`} />
              Refresh
            </button>
          </div>
        </div>
      </div>

      {loading ? (
        <div className="py-20 flex flex-col items-center justify-center text-slate-400 gap-4">
          <div className="relative">
            <div className="w-12 h-12 rounded-full border-2 border-blue-500/30 border-t-blue-500 animate-spin" />
            <Sparkles className="w-5 h-5 text-blue-400 absolute inset-0 m-auto animate-pulse" />
          </div>
          <p className="text-sm font-medium animate-pulse">
            Analyzing global sources and synthesizing your {briefingTime} briefing...
          </p>
        </div>
      ) : briefing ? (
        <div className="space-y-6">
          {/* Briefing Player & Quick Control */}
          <div className="bg-slate-900/80 border border-slate-800 rounded-2xl p-5 shadow-sm flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
            <div className="flex items-center gap-4">
              <button
                onClick={toggleAudio}
                className={`w-12 h-12 rounded-full flex items-center justify-center transition-all ${
                  isPlaying
                    ? 'bg-amber-500 text-slate-950 shadow-lg shadow-amber-500/20'
                    : 'bg-blue-600 hover:bg-blue-500 text-white shadow-lg shadow-blue-500/20'
                }`}
                title={isPlaying ? 'Pause Audio' : 'Listen to Briefing'}
              >
                {isPlaying ? <Pause className="w-5 h-5 fill-current" /> : <Play className="w-5 h-5 fill-current ml-0.5" />}
              </button>
              <div>
                <h3 className="font-semibold text-slate-100 text-base">
                  {briefing.title || `${briefing.timeOfDay} Executive Briefing`}
                </h3>
                <div className="flex items-center gap-3 text-xs text-slate-400 mt-0.5">
                  <span className="flex items-center gap-1">
                    <Calendar className="w-3.5 h-3.5" /> {briefing.date || new Date().toLocaleDateString()}
                  </span>
                  <span className="flex items-center gap-1">
                    <Clock className="w-3.5 h-3.5" /> 2 Min Listen
                  </span>
                </div>
              </div>
            </div>

            <div className="flex items-center gap-2 self-end sm:self-auto">
              <button
                onClick={handleShare}
                className="px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs font-medium flex items-center gap-1.5 transition-colors"
              >
                {copied ? <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" /> : <Share2 className="w-3.5 h-3.5" />}
                {copied ? 'Copied' : 'Share Briefing'}
              </button>
            </div>
          </div>

          {/* 30-Second Bullet Highlights */}
          {bullets.length > 0 && (
            <div className="bg-slate-900/60 border border-slate-800/80 rounded-2xl p-6 space-y-4">
              <div className="flex items-center gap-2 text-amber-400 font-semibold text-sm">
                <Sparkles className="w-4 h-4" /> 30-Second Executive Summary
              </div>
              <ul className="grid gap-3 sm:grid-cols-2">
                {bullets.map((bullet: string, idx: number) => (
                  <li
                    key={idx}
                    className="bg-slate-800/40 border border-slate-800 rounded-xl p-3.5 text-slate-200 text-xs leading-relaxed flex items-start gap-2.5"
                  >
                    <span className="w-5 h-5 rounded-full bg-blue-500/20 text-blue-400 flex items-center justify-center font-semibold text-[10px] shrink-0 mt-0.5">
                      {idx + 1}
                    </span>
                    <span>{bullet}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}

          {/* Key Topic Sections */}
          <div className="space-y-6">
            <h3 className="text-lg font-bold text-slate-100 flex items-center gap-2">
              <Compass className="w-5 h-5 text-blue-400" /> Topic Breakdown
            </h3>

            <div className="grid gap-6 md:grid-cols-2">
              {sections.map((section: any, idx: number) => (
                <div
                  key={idx}
                  className="bg-slate-900/80 border border-slate-800 hover:border-slate-700 rounded-2xl p-5 space-y-4 transition-all shadow-sm flex flex-col justify-between"
                >
                  <div className="space-y-3">
                    <div className="flex items-center justify-between border-b border-slate-800 pb-2">
                      <span className="px-2.5 py-1 rounded-md bg-indigo-500/10 text-indigo-400 border border-indigo-500/20 text-xs font-semibold">
                        {section.category}
                      </span>
                      <span className="text-[11px] text-slate-500 font-medium">
                        {(section.articles || []).length} Source Articles
                      </span>
                    </div>

                    <h4 className="font-bold text-slate-100 text-base leading-snug">
                      {section.topicTitle}
                    </h4>

                    <p className="text-slate-300 text-xs leading-relaxed">
                      {section.summary}
                    </p>
                  </div>

                  {section.articles && section.articles.length > 0 && (
                    <div className="pt-3 border-t border-slate-800/80 space-y-2">
                      <p className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider">
                        Related Articles:
                      </p>
                      <div className="space-y-1.5">
                        {section.articles.map((art: NewsArticle) => (
                          <div
                            key={art.id}
                            onClick={() => onSelectArticle(art)}
                            className="group flex items-center justify-between text-xs text-slate-300 hover:text-blue-400 cursor-pointer py-1 px-2 rounded-lg hover:bg-slate-800/60 transition-all"
                          >
                            <span className="truncate max-w-[80%] font-medium">
                              • {art.title}
                            </span>
                            <span className="text-[10px] text-slate-500 shrink-0 group-hover:text-blue-400">
                              Read &rarr;
                            </span>
                          </div>
                        ))}
                      </div>
                    </div>
                  )}
                </div>
              ))}
            </div>
          </div>
        </div>
      ) : (
        <div className="text-center py-12 text-slate-500 text-sm">
          No briefing available. Click refresh to generate one.
        </div>
      )}
    </div>
  );
};
