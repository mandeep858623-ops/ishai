/**
 * 2. REAL MICROSOFT POWERPOINT (.PPTX) EXPORTER
 * Generates genuine 16:9 widescreen PowerPoint presentation files with editable text,
 * formatted slides, card containers, and attached speaker notes.
 */
export async function exportToPptx(params: {
  title: string;
  subtitle?: string;
  slides: SlideData[];
  theme?: PPTTheme;
  author?: string;
}): Promise<Blob> {
  const { title, subtitle = '', slides, theme = 'emerald', author = 'SUPERAI PPT Maker' } = params;
  const studioTheme = STUDIO_THEMES[theme as FullPPTTheme];
  const colors = studioTheme
    ? {
        bg: studioTheme.hexBg,
        cardBg: studioTheme.hexCardBg,
        accent: studioTheme.hexAccent,
        titleColor: studioTheme.hexTitle,
        textColor: studioTheme.hexText,
        secondaryText: '94A3B8',
      }
    : THEME_CONFIGS[theme as keyof typeof THEME_CONFIGS] || THEME_CONFIGS.emerald;

  const pptx = new pptxgen();
  pptx.layout = 'LAYOUT_16x9';
  pptx.title = title;
  pptx.author = author;
  pptx.company = 'SUPERAI';

  // 1. Cover Slide
  const cover = pptx.addSlide();
  cover.background = { color: colors.bg };

  // Decorative Accent bar
  cover.addShape(pptx.ShapeType.rect, {
    x: 0.8,
    y: 2.0,
    w: 0.15,
    h: 3.2,
    fill: { color: colors.accent },
  });

  // Main Deck Title
  cover.addText(title, {
    x: 1.2,
    y: 2.0,
    w: 11.0,
    h: 1.8,
    fontSize: 44,
    bold: true,
    color: colors.titleColor,
    fontFace: 'Arial',
    valign: 'middle',
  });

  // Subtitle
  if (subtitle || title) {
    cover.addText(subtitle || 'Complete Presentation Deck', {
      x: 1.2,
      y: 3.9,
      w: 11.0,
      h: 0.8,
      fontSize: 20,
      color: colors.secondaryText,
      fontFace: 'Arial',
    });
  }

  // Footer Tag
  cover.addText(`SUPERAI Presentation Studio • ${new Date().toLocaleDateString()}`, {
    x: 1.2,
    y: 6.2,
    w: 8.0,
    h: 0.5,
    fontSize: 12,
    color: colors.secondaryText,
    fontFace: 'Arial',
  });

  // 2. Content Slides
  slides.forEach((slideData, idx) => {
    const slide = pptx.addSlide();
    slide.background = { color: colors.bg };

    // Header Category / Number Indicator
    slide.addText(`SLIDE ${idx + 1} OF ${slides.length} • ${title.toUpperCase()}`, {
      x: 0.8,
      y: 0.45,
      w: 11.5,
      h: 0.35,
      fontSize: 10,
      bold: true,
      color: colors.accent,
      fontFace: 'Arial',
    });

    // Slide Title
    slide.addText(slideData.title, {
      x: 0.8,
      y: 0.85,
      w: 11.5,
      h: 0.9,
      fontSize: 28,
      bold: true,
      color: colors.titleColor,
      fontFace: 'Arial',
    });

    // Decorative underline
    slide.addShape(pptx.ShapeType.rect, {
      x: 0.8,
      y: 1.8,
      w: 11.5,
      h: 0.03,
      fill: { color: colors.accent },
    });

    // Check if there is a takeaway or right card
    const hasTakeaway = Boolean(slideData.takeaway);
    const bulletsWidth = hasTakeaway ? 7.6 : 11.4;

    // Bullet points card container
    slide.addShape(pptx.ShapeType.roundRect, {
      x: 0.8,
      y: 2.1,
      w: bulletsWidth,
      h: 4.6,
      fill: { color: colors.cardBg },
      line: { color: colors.accent, width: 1 },
      rectRadius: 0.1,
    });

    // Format bullets
    const bulletsFormatted = slideData.bulletPoints.map((pt) => ({
      text: pt,
      options: {
        fontSize: 15,
        color: colors.textColor,
        fontFace: 'Arial',
        bullet: true,
        breakLine: true,
        paraSpaceAfter: 12,
      },
    }));

    if (bulletsFormatted.length > 0) {
      slide.addText(bulletsFormatted, {
        x: 1.1,
        y: 2.4,
        w: bulletsWidth - 0.6,
        h: 4.0,
        valign: 'top',
      });
    }

    // Right side Takeaway / Key Highlight Card
    if (hasTakeaway) {
      slide.addShape(pptx.ShapeType.roundRect, {
        x: 8.7,
        y: 2.1,
        w: 3.8,
        h: 4.6,
        fill: { color: colors.cardBg },
        line: { color: colors.accent, width: 1 },
        rectRadius: 0.1,
      });

      slide.addText('💡 KEY TAKEAWAY', {
        x: 9.0,
        y: 2.4,
        w: 3.2,
        h: 0.4,
        fontSize: 12,
        bold: true,
        color: colors.accent,
        fontFace: 'Arial',
      });

      slide.addText(slideData.takeaway || '', {
        x: 9.0,
        y: 2.9,
        w: 3.2,
        h: 3.4,
        fontSize: 14,
        color: colors.textColor,
        fontFace: 'Arial',
        valign: 'top',
      });
    }

    // Speaker Notes attached to slide
    if (slideData.speakerNotes) {
      slide.addNotes(slideData.speakerNotes);
    }
  });

  const blob = (await pptx.write({ outputType: 'blob' })) as Blob;
  return blob;
}

/**
 * 3. REAL PDF (.PDF) EXPORTER
 * Generates genuine PDF files with selectable text, clean margins,
 * formatted headings, running headers, and page pagination.
 */
export function exportToPdf(params: {
  title: string;
  content: string;
  category?: string;
  author?: string;
}): Blob {
  const { title, content, category = 'Document', author = 'SUPERAI' } = params;
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  let cursorY = margin;

  const rawLines = cleanText(content).split('\n');

  // Document Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.setTextColor(26, 35, 126); // Deep Indigo
  const titleLines = doc.splitTextToSize(title, contentWidth);
  doc.text(titleLines, margin, cursorY);
  cursorY += titleLines.length * 8 + 4;

  // Metadata Subtitle
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(`${category.toUpperCase()} • Generated via ${author} • ${new Date().toLocaleDateString()}`, margin, cursorY);
  cursorY += 6;

  // Divider line
  doc.setDrawColor(203, 213, 225);
  doc.setLineWidth(0.5);
  doc.line(margin, cursorY, pageWidth - margin, cursorY);
  cursorY += 8;

  // Check page overflow
  const ensureSpace = (neededHeight: number) => {
    if (cursorY + neededHeight > pageHeight - margin - 10) {
      doc.addPage();
      cursorY = margin + 10;
      // Running header on page 2+
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(title, margin, margin);
      doc.line(margin, margin + 2, pageWidth - margin, margin + 2);
    }
  };

  // Content rendering
  for (const line of rawLines) {
    const trimmed = line.trim();
    if (!trimmed) {
      cursorY += 4;
      continue;
    }

    // Heading 1
    if (trimmed.startsWith('# ') || trimmed.startsWith('## ')) {
      ensureSpace(14);
      const hText = trimmed.replace(/^#{1,2}\s+/, '');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(14);
      doc.setTextColor(30, 41, 59);
      const hLines = doc.splitTextToSize(hText, contentWidth);
      doc.text(hLines, margin, cursorY);
      cursorY += hLines.length * 6 + 3;
    }
    // Heading 2
    else if (trimmed.startsWith('### ') || trimmed.startsWith('#### ')) {
      ensureSpace(12);
      const hText = trimmed.replace(/^#{3,4}\s+/, '');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      doc.setTextColor(51, 65, 85);
      const hLines = doc.splitTextToSize(hText, contentWidth);
      doc.text(hLines, margin, cursorY);
      cursorY += hLines.length * 5 + 2;
    }
    // Bullet item
    else if (/^[-*•]\s+/.test(trimmed)) {
      const bText = trimmed.replace(/^[-*•]\s+/, '').replace(/\*\*/g, '');
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(51, 65, 85);
      const bulletLines = doc.splitTextToSize(bText, contentWidth - 6);
      ensureSpace(bulletLines.length * 5 + 2);
      doc.text('•', margin + 1, cursorY);
      doc.text(bulletLines, margin + 6, cursorY);
      cursorY += bulletLines.length * 4.8 + 2;
    }
    // Standard paragraph
    else {
      const pText = trimmed.replace(/\*\*/g, '');
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(30, 41, 59);
      const pLines = doc.splitTextToSize(pText, contentWidth);
      ensureSpace(pLines.length * 5 + 3);
      doc.text(pLines, margin, cursorY);
      cursorY += pLines.length * 4.8 + 3;
    }
  }

  // Add Page Numbers to all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(148, 163, 184);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - margin - 15, pageHeight - 8);
  }

  return doc.output('blob');
}

/**
 * Triggers browser download for a Blob
 */
export function triggerFileDownload(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
