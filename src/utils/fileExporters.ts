import { Document, Paragraph, TextRun, HeadingLevel, AlignmentType, Packer, BorderStyle } from 'docx';
import pptxgen from 'pptxgenjs';
import { jsPDF } from 'jspdf';

/**
 * Clean and normalize text strings
 */
function cleanText(text: string): string {
  return text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
}

/**
 * 1. REAL MICROSOFT WORD (.DOCX) EXPORTER
 * Generates genuine Microsoft Word documents with structured headings,
 * styled paragraphs, bullet lists, and header/footer metadata.
 */
export async function exportToDocx(params: {
  title: string;
  content: string;
  author?: string;
  category?: string;
}): Promise<Blob> {
  const { title, content, author = 'SUPERAI Document Engine', category = 'General' } = params;
  const rawLines = cleanText(content).split('\n');

  const docChildren: Paragraph[] = [];

  // Title Block
  docChildren.push(
    new Paragraph({
      heading: HeadingLevel.TITLE,
      alignment: AlignmentType.CENTER,
      spacing: { before: 200, after: 120 },
      children: [
        new TextRun({
          text: title,
          bold: true,
          size: 40, // 20pt
          color: '0D47A1',
          font: 'Calibri',
        }),
      ],
    })
  );

  // Subtitle / Meta Tag
  docChildren.push(
    new Paragraph({
      alignment: AlignmentType.CENTER,
      spacing: { after: 360 },
      children: [
        new TextRun({
          text: `Generated via ${author} | ${category} | ${new Date().toLocaleDateString()}`,
          italics: true,
          size: 18, // 9pt
          color: '757575',
          font: 'Calibri',
        }),
      ],
    })
  );

  // Horizontal divider separator
  docChildren.push(
    new Paragraph({
      spacing: { after: 240 },
      border: {
        bottom: {
          color: 'B0BEC5',
          size: 6,
          style: BorderStyle.SINGLE,
        },
      },
      children: [],
    })
  );

  // Parse lines into Headings, Bullets, and Paragraphs
  for (const line of rawLines) {
    const trimmed = line.trim();
    if (!trimmed) {
      docChildren.push(new Paragraph({ spacing: { after: 120 }, children: [] }));
      continue;
    }

    // Heading Level 1 (# Heading or ### Heading)
    if (trimmed.startsWith('# ') || trimmed.startsWith('## ')) {
      const headingText = trimmed.replace(/^#{1,2}\s+/, '');
      docChildren.push(
        new Paragraph({
          heading: HeadingLevel.HEADING_1,
          spacing: { before: 280, after: 120 },
          children: [
            new TextRun({
              text: headingText,
              bold: true,
              size: 28, // 14pt
              color: '1565C0',
              font: 'Calibri',
            }),
          ],
        })
      );
    }
    // Heading Level 2 (### Heading or #### Heading)
    else if (trimmed.startsWith('### ') || trimmed.startsWith('#### ')) {
      const headingText = trimmed.replace(/^#{3,4}\s+/, '');
      docChildren.push(
        new Paragraph({
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 200, after: 80 },
          children: [
            new TextRun({
              text: headingText,
              bold: true,
              size: 24, // 12pt
              color: '2E7D32',
              font: 'Calibri',
            }),
          ],
        })
      );
    }
    // Bullet List Item (- bullet or * bullet)
    else if (/^[-*•]\s+/.test(trimmed)) {
      const bulletText = trimmed.replace(/^[-*•]\s+/, '');
      docChildren.push(
        new Paragraph({
          bullet: { level: 0 },
          spacing: { after: 60 },
          children: parseInlineFormatting(bulletText),
        })
      );
    }
    // Numbered List Item (1. Item)
    else if (/^\d+\.\s+/.test(trimmed)) {
      const numText = trimmed.replace(/^\d+\.\s+/, '');
      docChildren.push(
        new Paragraph({
          numbering: { reference: 'default-numbering', level: 0 },
          spacing: { after: 60 },
          children: parseInlineFormatting(numText),
        })
      );
    }
    // Standard Paragraph
    else {
      docChildren.push(
        new Paragraph({
          spacing: { after: 140, line: 276 }, // 1.15 line spacing
          children: parseInlineFormatting(trimmed),
        })
      );
    }
  }

  const doc = new Document({
    creator: author,
    title,
    description: `Generated by SUPERAI Document Engine`,
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: 1440, // 1 inch (1440 dxa)
              right: 1440,
              bottom: 1440,
              left: 1440,
            },
          },
        },
        children: docChildren,
      },
    ],
  });

  return await Packer.toBlob(doc);
}

/**
 * Helper to parse bold (**bold**) and italic (*italic*) into TextRuns
 */
function parseInlineFormatting(text: string): TextRun[] {
  const runs: TextRun[] = [];
  const regex = /(\*\*.*?\*\*|\*.*?\*)/g;
  const parts = text.split(regex);

  for (const part of parts) {
    if (!part) continue;
    if (part.startsWith('**') && part.endsWith('**')) {
      runs.push(
        new TextRun({
          text: part.slice(2, -2),
          bold: true,
          font: 'Calibri',
          size: 22, // 11pt
          color: '212121',
        })
      );
    } else if (part.startsWith('*') && part.endsWith('*')) {
      runs.push(
        new TextRun({
          text: part.slice(1, -1),
          italics: true,
          font: 'Calibri',
          size: 22,
          color: '424242',
        })
      );
    } else {
      runs.push(
        new TextRun({
          text: part,
          font: 'Calibri',
          size: 22,
          color: '212121',
        })
      );
    }
  }

  return runs.length > 0 ? runs : [new TextRun({ text, font: 'Calibri', size: 22, color: '212121' })];
}

